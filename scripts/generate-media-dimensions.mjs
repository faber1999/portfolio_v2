// Scans public/images/projects/**/* for images and writes their intrinsic width/height to
// src/data/media-dimensions.generated.ts, keyed by public path ('/images/projects/<slug>/<file>').
// Runs automatically before `dev` and `build-only` (see package.json "gen:media").
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import { imageSize } from 'image-size'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const publicDir = join(root, 'public')
const scanDir = join(publicDir, 'images', 'projects')
const outFile = join(root, 'src', 'data', 'media-dimensions.generated.ts')
const IMAGE_EXT = /\.(webp|avif|png|jpe?g)$/i

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) return walk(path)
    return entry.isFile() && IMAGE_EXT.test(entry.name) ? [path] : []
  })
}

const entries = walk(scanDir)
  .map((file) => {
    const { width, height, orientation } = imageSize(readFileSync(file))
    if (!width || !height) throw new Error(`Could not read dimensions of ${file}`)
    // EXIF orientations 5-8 rotate the image 90deg, so the rendered box is swapped.
    const rotated = orientation !== undefined && orientation >= 5
    const key = '/' + relative(publicDir, file).split(sep).join('/')
    return [key, rotated ? { width: height, height: width } : { width, height }]
  })
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))

const lines = entries.map(
  ([key, { width, height }]) => `  '${key}': { width: ${width}, height: ${height} },`,
)

const content = `// AUTO-GENERATED by scripts/generate-media-dimensions.mjs. DO NOT EDIT.
// Regenerate with \`pnpm gen:media\` (runs automatically before dev and build).

export const generatedMediaDimensions: Record<string, { width: number; height: number }> = {
${lines.join('\n')}
}
`

let previous = ''
try {
  previous = readFileSync(outFile, 'utf8')
} catch {
  // first run
}
if (previous !== content) writeFileSync(outFile, content)
console.log(
  `[gen:media] ${entries.length} images -> ${relative(root, outFile).split(sep).join('/')}${previous === content ? ' (unchanged)' : ''}`,
)
